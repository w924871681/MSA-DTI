"""Regenerate the budget-feasibility and final-model-selection figure.

Left: exact Gaussian-weighted mean of feasible counts over the complete budget domain.
Right: artists generated by the archived paper plotting code from its CSVs.
Run with Python from any directory. All inputs are relative to this file.
"""
from math import erfc, sqrt
from pathlib import Path
import json
import sys
from unittest.mock import patch

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap, Normalize, to_rgb
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "plotting"))
import plot_figures as archived

PARAMETER_RANGE = (2_081.0, 100_000.0)
OPERATION_RANGE = (155_712.0, 1_250_000.0)
SIGMA_FRACTION = 0.10  # Gaussian standard deviation / full linear axis span.
ERFC = np.vectorize(erfc, otypes=[np.float64])


def read_costs():
    records = json.loads((ROOT / "data" / "budget_resource_profiles_new.json").read_text(encoding="utf-8"))
    profiles = records["1"]
    assert len(profiles) == 19
    return np.array([(x["parameters"], x["operations"]) for x in profiles.values()])


def passing_fraction(centers, requirements, limits, sigma=SIGMA_FRACTION):
    """Share of the normalized, domain-truncated Gaussian above a requirement."""
    low, high = limits
    if sigma <= 0:
        raise ValueError("sigma must be positive")
    centers = np.asarray(centers, dtype=float)[..., None]
    requirements = np.asarray(requirements, dtype=float)
    if np.any((centers < low) | (centers > high)):
        raise ValueError("Budget centers must be inside the scan range")
    scale = sqrt(2) * sigma * (high - low)
    upper_tail = ERFC((high - centers) / scale)
    mass = ERFC((low - centers) / scale) - upper_tail
    passing = ERFC((np.clip(requirements, low, high) - centers) / scale) - upper_tail
    return passing / mass


def weighted_mean(p, f, costs, sigma=SIGMA_FRACTION):
    """Weighted mean of the exact two-constraint count over all budget pairs."""
    wp = passing_fraction(p, costs[:, 0], PARAMETER_RANGE, sigma)
    wf = passing_fraction(f, costs[:, 1], OPERATION_RANGE, sigma)
    return np.sum(wp * wf, axis=-1)


def plot_surface(fig, costs):
    # Separable weights: evaluate each probability at each of the 1-D grid
    # coordinates once, then form the exact sum of the candidate-specific joint probabilities.
    p = np.linspace(*PARAMETER_RANGE, 193)
    f = np.linspace(*OPERATION_RANGE, 193)
    pp, ff = np.meshgrid(p, f)
    wp = passing_fraction(p, costs[:, 0], PARAMETER_RANGE)
    wf = passing_fraction(f, costs[:, 1], OPERATION_RANGE)
    z = wf @ wp.T
    count = len(costs)
    assert np.all((z >= 0) & (z <= count))
    assert np.all(np.diff(z, axis=0) >= -1e-12) and np.all(np.diff(z, axis=1) >= -1e-12)
    ax = fig.add_axes([.025, .181, .471, .777], projection="3d", computed_zorder=False)
    cmap = LinearSegmentedColormap.from_list("feasibility", [
        "#e9f1e9", "#b9d8ce", "#78b9af", "#37868a", "#185665", "#173d53"
    ], N=2048)
    ax.plot_surface(pp / 1000, ff / 1e6, z, cmap=cmap, norm=Normalize(0, count),
                    rcount=len(f), ccount=len(p), linewidth=0, antialiased=False,
                    shade=False, rasterized=True, zorder=1)
    # View from the tight corner. Moving away from the camera, both caps
    # loosen and the surface rises, so the sparse iso-budget sections are visible.
    for center in np.linspace(*PARAMETER_RANGE, 9):
        ax.plot(np.full_like(f, center) / 1000, f / 1e6, weighted_mean(center, f, costs),
                color="#224955", alpha=.52, lw=.32, zorder=3)
    for center in np.linspace(*OPERATION_RANGE, 9):
        ax.plot(p / 1000, np.full_like(p, center) / 1e6, weighted_mean(p, center, costs),
                color="#224955", alpha=.52, lw=.32, zorder=3)
    ax.set(xlim=(p[-1] / 1000, p[0] / 1000), ylim=(f[-1] / 1e6, f[0] / 1e6),
           zlim=(0, count), zticks=[0, 5, 10, 15, 19])
    ax.set_xticks([25, 50, 75, 100])
    ax.set_yticks([.25, .50, .75, 1.00, 1.25], ["0.25", "0.50", "0.75", "1.00", "1.25"])
    ax.set_xlabel("Parameter cap (thousands)", labelpad=1.0)
    ax.set_ylabel("Compute cap (M FLOPs)", labelpad=1.0)
    ax.set_zlabel("Mean feasible candidates", labelpad=1.0)
    ax.tick_params(labelsize=9, pad=0)
    ax.view_init(elev=30, azim=42)
    ax.set_proj_type("ortho")
    ax.set_box_aspect((1.25, 1.06, .90), zoom=.96)
    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
        axis.set_pane_color((.975, .981, .979, 1))
        axis._axinfo["grid"].update(color="#d6e0dd", linewidth=.45)


    return ax


def luminance(rgb):
    rgb = np.asarray(rgb)
    linear = np.where(rgb <= .04045, rgb/12.92, ((rgb+.055)/1.055)**2.4)
    return float(np.dot(linear, [.2126, .7152, .0722]))


def check_cell_text(heatmap):
    """Preserve native heatmap colours and improve only low-contrast annotations."""
    image = heatmap.images[0]
    values = image.get_array()
    for text in heatmap.texts:
        col, row = map(int, text.get_position())
        bg = luminance(image.cmap(image.norm(values[row, col]))[:3])
        fg = luminance(to_rgb(text.get_color()))
        if (max(bg, fg) + .05)/(min(bg, fg) + .05) < 4.5:
            text.set_color("black" if (bg+.05)/.05 > 1.05/(bg+.05) else "white")


def main():
    # Preserve the 3D surface styling. Group rarely selected configurations in
    # the heat map so the 19-record bank remains legible at paper width.
    from collections import Counter
    import pandas as pd
    archived.style()
    fig = archived.canvas(217)
    selection = fig.add_axes([.640, .177, .253, .699])
    colorbar = fig.add_axes([.913, .177, .013, .699])
    rows = pd.read_csv(ROOT / 'data' / 'budget_selection_new.csv')
    top = [int(q) for q,_ in Counter(rows.arch).most_common(6)]
    rates = np.array([[100 * ((rows.budget == b) & (rows.arch == q)).sum() / 120 for b in ('tight','medium','loose')] for q in top])
    rates = np.vstack([rates, 100-rates.sum(axis=0)])
    image = selection.imshow(rates,cmap='GnBu',vmin=0,vmax=60,aspect='auto',interpolation='nearest')
    selection.set_xticks([0,1,2],['Tight','Medium','Loose'])
    selection.set_yticks(range(7),[f'A{x}' + (' (ref.)' if x==57 else '') for x in top]+['Other'])
    selection.tick_params(length=3,width=.7,pad=3)
    for i in range(7):
        for j in range(3):selection.text(j,i,f'{rates[i,j]:.1f}%',ha='center',va='center',color='white' if rates[i,j]>=33 else '#333333')
    cb=fig.colorbar(image,cax=colorbar,ticks=range(0,61,15));cb.set_label('Selection rate (%)',labelpad=4)

    assert rates.shape == (7, 3) and np.allclose(rates.sum(axis=0), 100)
    check_cell_text(selection)
    surface = plot_surface(fig, read_costs())
    archived.panel_row(fig, [(surface, "(a) Weighted feasible count (H = 1)"),
                             (selection, "(b) Final model selection")])
    fig.savefig(ROOT / "figures" / "budget_feasibility.pdf", dpi=600, metadata={
        "Title":"Budget feasibility and final model selection",
        "Creator":"MSA-DTI figure reproduction", "CreationDate":None, "ModDate":None})
    (ROOT / "generated_figures").mkdir(exist_ok=True)
    fig.savefig(ROOT / "generated_figures" / "budget_feasibility.png", dpi=600)
    plt.close(fig)


if __name__ == "__main__":
    main()
